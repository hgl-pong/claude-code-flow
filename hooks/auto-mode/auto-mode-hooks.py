#!/usr/bin/env python3
"""Auto-mode hook helpers — shared JSON parsing and state detection."""

import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone
from typing import Optional


def read_state_files() -> list[str]:
    """Find all state.json files under .claude/auto/."""
    auto_dir = ".claude/auto"
    if not os.path.isdir(auto_dir):
        return []
    state_files = []
    for task_dir in os.listdir(auto_dir):
        sf = os.path.join(auto_dir, task_dir, "state.json")
        if os.path.isfile(sf):
            state_files.append(sf)
    return sorted(state_files)


def load_json(path: str) -> Optional[dict]:
    """Load and parse a JSON file."""
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except (json.JSONDecodeError, IOError):
        return None


def auto_mode_active() -> Optional[str]:
    """Return the path to the most recently updated active state.json, or None."""
    latest_file = None
    latest_time = ""
    for sf in read_state_files():
        data = load_json(sf)
        if not data:
            continue
        status = data.get("status", "")
        if status in ("DONE", "STOPPED_ASK_USER"):
            continue
        updated = data.get("updated_at", "")
        if updated > latest_time:
            latest_time = updated
            latest_file = sf
    return latest_file


def generate_resume_prompt(state_file: str) -> str:
    """Generate a state-aware resume prompt for the Stop hook."""
    data = load_json(state_file)
    if not data:
        return "AUTO-MODE CONTINUATION: State file unreadable."

    task_name = data.get("task_name", "unknown")
    phase = data.get("phase", "unknown")
    step = data.get("current_step", "unknown")
    status = data.get("status", "unknown")
    progress = data.get("progress", {})
    tasks_total = progress.get("tasks_total", 0)
    tasks_completed = progress.get("tasks_completed", 0)

    runtime = data.get("runtime_verification", {})
    runtime_status = runtime.get("status", "unknown")
    smoke_status = runtime.get("smoke", "unknown")
    crash_detected = runtime.get("crash_detected", False)
    hang_detected = runtime.get("hang_detected", False)
    evidence_dir = runtime.get("evidence_dir", "")

    # Task states summary
    task_states = data.get("task_states", {})
    ts_summary = ", ".join(
        f"{k}={v.get('status', '?')}" for k, v in task_states.items()
    ) or "none"

    # Active agents summary
    active_agents = data.get("active_agents", [])
    aa_summary = ", ".join(
        f"{a.get('task_id', '?')}({a.get('role', '?')})" for a in active_agents
    ) or "none"

    # Failing gates
    gate_states = data.get("gate_states", {})
    failing = ", ".join(
        k for k, v in gate_states.items() if not v.get("passed", False)
    ) or "none"

    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    return f"""AUTO-MODE CONTINUATION — task: {task_name}, phase: {phase}, step: {step}, status: {status}

You are in auto-mode. DO NOT STOP. Read the state file at {state_file} for full details.

Current state summary:
- Phase: {phase} | Step: {step} | Status: {status}
- Tasks: {tasks_completed}/{tasks_total} completed
- Task states: {ts_summary}
- Active agents: {aa_summary}
- Failing gates: {failing}
- Runtime evidence: {runtime_status} | smoke: {smoke_status} | crash: {crash_detected} | hang: {hang_detected}
- Evidence dir: {evidence_dir or 'none'}

Instructions by phase:
- brainstorming / writing-plans: Continue from current_step={step}. Auto-decide everything. Log to audit trail. Proceed to next phase when done.
- subagent-driven-development: Check git log for commits from active agents. Advance task_states for agents that completed. Re-dispatch failed/missing tasks. Fill pool to max_parallel_agents. If all tasks done, enter completion-gates.
- completion-gates: Run gates in order ({failing}). Do NOT re-check passed gates. After all 7 pass, enter finishing.
- finishing: Complete the merge, set status to DONE.

CRITICAL RULES:
1. Log every decision to .claude/auto/{task_name}/decisions.md
2. Write state.json BEFORE every state transition
3. Do NOT ask the user anything outside the 4 stop conditions
4. Do NOT stop until status is DONE
5. Check git log first if agents may have completed during your pause

Generated by auto-mode Stop hook at {ts}."""


def agent_is_tracked(state_file: str, agent_id: str) -> bool:
    """Check if an agent_id appears in the active_agents list."""
    data = load_json(state_file)
    if not data:
        return False
    return any(a.get("agent_id") == agent_id for a in data.get("active_agents", []))


def get_agent_role(state_file: str, agent_id: str) -> str:
    """Get the role of a tracked agent."""
    data = load_json(state_file)
    if not data:
        return ""
    for a in data.get("active_agents", []):
        if a.get("agent_id") == agent_id:
            return a.get("role", "")
    return ""


def has_pending_tasks(state_file: str) -> bool:
    """Check if any task_states entries have status != done/failed."""
    data = load_json(state_file)
    if not data:
        return False
    return any(
        v.get("status") not in ("done", "failed")
        for v in data.get("task_states", {}).values()
    )


def emit_json(obj: dict) -> None:
    """Print JSON to stdout for hook decision."""
    print(json.dumps(obj))


def emit_context_json(context: str, event_name: str) -> None:
    """Print hookSpecificOutput JSON for context injection hooks."""
    obj = {
        "hookSpecificOutput": {
            "hookEventName": event_name,
            "additionalContext": context,
        }
    }
    print(json.dumps(obj))


# ---------- CLI entry points for each hook ----------

def hook_stop():
    """Stop hook: block if auto-mode active."""
    sf = auto_mode_active()
    if not sf:
        sys.exit(0)
    reason = generate_resume_prompt(sf)
    emit_json({"decision": "block", "reason": reason})
    sys.exit(0)


def hook_subagent_stop():
    """SubagentStop hook: block subagent if tracked and no output/commit."""
    sf = auto_mode_active()
    if not sf:
        sys.exit(0)

    raw = sys.stdin.read().strip()
    try:
        inp = json.loads(raw)
    except json.JSONDecodeError:
        sys.exit(0)

    agent_id = inp.get("agent_id", "")
    agent_type = inp.get("agent_type", "")
    last_message = inp.get("last_assistant_message", "")

    if not agent_is_tracked(sf, agent_id):
        sys.exit(0)

    role = get_agent_role(sf, agent_id)
    is_implementer = (role == "implementer" or agent_type == "general-purpose")

    # Tier 1: empty output
    if not last_message:
        if is_implementer:
            reason = "AUTO-MODE SUBAGENT: No output. Implement the task, run tests, commit to git. DO NOT STOP without a commit."
        else:
            reason = "AUTO-MODE SUBAGENT: No output. Complete your review and provide findings. DO NOT STOP without producing output."
        emit_json({"decision": "block", "reason": reason})
        sys.exit(0)

    # Tier 2: gave-up language
    gave_up = re.compile(
        r"(cannot proceed|cannot complete|unable to complete|unable to proceed|need more information|need you to clarify|I need you to|please clarify|I give up|what should I do next)",
        re.IGNORECASE,
    )
    if gave_up.search(last_message):
        reason = """AUTO-MODE SUBAGENT: You appear stuck. In auto-mode, no questions allowed.
Search the codebase, pick the simplest approach, make your own decisions.
Continue working. Produce output with concrete results."""
        emit_json({"decision": "block", "reason": reason})
        sys.exit(0)

    # Tier 3: no recent git commit — implementers only
    if is_implementer:
        try:
            result = subprocess.run(
                ["git", "log", "--since=5 minutes ago", "--oneline"],
                capture_output=True, text=True,
            )
            if not result.stdout.strip():
                reason = "AUTO-MODE SUBAGENT: No git commit. As implementer you must produce a commit. Implemented? Tested? Committed? If yes, mention the commit hash. If no, do the work."
                emit_json({"decision": "block", "reason": reason})
                sys.exit(0)
        except Exception:
            pass

    sys.exit(0)


def hook_subagent_start():
    """SubagentStart hook: inject auto-mode context."""
    sf = auto_mode_active()
    if not sf:
        sys.exit(0)

    data = load_json(sf)
    task_name = data.get("task_name", "unknown") if data else "unknown"
    phase = data.get("phase", "unknown") if data else "unknown"

    context = f"""<AUTO-MODE-CONTEXT>
You are a subagent in an auto-mode pipeline (task: {task_name}, phase: {phase}).
The main agent runs autonomously and expects you to complete your task without questions.

RULES:
1. Make all decisions yourself — do NOT ask clarifying questions
2. Search the codebase if you need context
3. Always commit your work to git before stopping
4. Follow existing project patterns
5. Debug and fix test failures yourself
6. Output concrete results: files changed, commits made
7. Do NOT stop with "I need more information"
8. Pick the simplest working approach if unsure

State file: {sf}
</AUTO-MODE-CONTEXT>"""
    emit_context_json(context, "SubagentStart")
    sys.exit(0)


def hook_pre_compact():
    """PreCompact hook: write snapshot before compaction."""
    sf = auto_mode_active()
    if not sf:
        sys.exit(0)

    inp_raw = sys.stdin.read().strip()
    trigger = "auto"
    try:
        inp = json.loads(inp_raw)
        trigger = inp.get("trigger", "auto")
    except json.JSONDecodeError:
        pass

    data = load_json(sf)
    if not data:
        sys.exit(0)

    task_name = data.get("task_name", "unknown")
    snapshot_dir = f".claude/auto/{task_name}"
    snapshot_file = f"{snapshot_dir}/compact-snapshot.md"
    os.makedirs(snapshot_dir, exist_ok=True)

    recent_git = ""
    try:
        r = subprocess.run(["git", "log", "--oneline", "-10"], capture_output=True, text=True)
        recent_git = r.stdout.strip()
    except Exception:
        recent_git = "(no git history)"

    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    phase = data.get("phase", "?")
    step = data.get("current_step", "?")
    status = data.get("status", "?")
    progress = data.get("progress", {})
    tc = progress.get("tasks_completed", 0)
    tt = progress.get("tasks_total", 0)

    runtime = data.get("runtime_verification", {})
    runtime_status = runtime.get("status", "unknown")
    smoke_status = runtime.get("smoke", "unknown")
    crash_detected = runtime.get("crash_detected", False)
    hang_detected = runtime.get("hang_detected", False)
    evidence_dir = runtime.get("evidence_dir", "")

    task_states = data.get("task_states", {})
    ts_lines = "\n".join(
        f"- **{k}**: status={v.get('status', '?')}, attempts={v.get('attempts', 0)}"
        for k, v in task_states.items()
    ) or "No task states"

    gate_states = data.get("gate_states", {})
    gs_lines = "\n".join(
        f"- **{k}**: passed={v.get('passed', False)}, iterations={v.get('iterations', 0)}"
        for k, v in gate_states.items()
    ) or "No gate states"

    active_agents = data.get("active_agents", [])
    aa_lines = "\n".join(
        f"- **{a.get('task_id', '?')}** ({a.get('role', '?')}): dispatched {a.get('dispatched_at', '?')}"
        for a in active_agents
    ) or "(none)"

    snapshot = f"""# Auto-Mode Compaction Snapshot

**Created:** {ts}
**Trigger:** {trigger}

## Pipeline State

| Field | Value |
|-------|-------|
| Phase | {phase} |
| Step | {step} |
| Status | {status} |
| Tasks | {tc} / {tt} |

## Task States

{ts_lines}

## Gate States

{gs_lines}

## Runtime Verification

- Status: {runtime_status}
- Smoke: {smoke_status}
- Crash detected: {crash_detected}
- Hang detected: {hang_detected}
- Evidence dir: {evidence_dir}

## Active Agents at Compaction Time

{aa_lines}

## Recent Commits

```
{recent_git}
```

## Recovery Instructions

After compaction, read this file to restore your mental model:

1. Phase: **{phase}**, Step: **{step}**
2. Tasks done: {tc} / {tt}
3. Re-queue only tasks with status "failed" or "queued" in task_states
4. Re-run only gates with passed=false in gate_states
5. Check runtime_verification before re-dispatching smoke tests
6. Check git log for active_agents above before re-dispatching
7. Main state file: {sf}
8. Continue. Do NOT redo completed work.
"""

    with open(snapshot_file, "w", encoding="utf-8") as f:
        f.write(snapshot)

    sys.stderr.write(f"Auto-mode: PreCompact snapshot → {snapshot_file}\n")
    sys.exit(0)


def hook_session_start():
    """SessionStart hook: detect dangling auto-mode tasks."""
    sf = auto_mode_active()
    if not sf:
        sys.exit(0)

    data = load_json(sf)
    if not data:
        sys.exit(0)

    task_name = data.get("task_name", "unknown")
    phase = data.get("phase", "unknown")
    status = data.get("status", "unknown")
    step = data.get("current_step", "unknown")
    updated = data.get("updated_at", "unknown")

    context = f"""<AUTO-MODE-DANGLING-TASK>
Auto-mode has a dangling task from a previous session.

Task: {task_name}
Phase: {phase}
Step: {step}
Status: {status}
Last updated: {updated}
State file: {sf}

Run: /auto --resume {task_name}
Start fresh: /auto --new <new task>
List all: /auto --list
</AUTO-MODE-DANGLING-TASK>"""

    emit_context_json(context, "SessionStart")
    sys.exit(0)


def hook_teammate_idle():
    """TeammateIdle hook: block teammate idle if pending tasks."""
    sf = auto_mode_active()
    if not sf:
        sys.exit(0)

    raw = sys.stdin.read().strip()
    try:
        inp = json.loads(raw)
    except json.JSONDecodeError:
        sys.exit(0)

    team_name = inp.get("team_name", "")
    if not team_name:
        sys.exit(0)

    if has_pending_tasks(sf):
        teammate_name = inp.get("teammate_name", "unknown")
        sys.stderr.write(
            f"AUTO-MODE: {teammate_name} going idle but pending tasks remain. "
            f"Check {sf}. Pick up next task.\n"
        )
        sys.exit(2)

    sys.exit(0)


# ---------- Main dispatch ----------

COMMANDS = {
    "stop": hook_stop,
    "subagent-stop": hook_subagent_stop,
    "subagent-start": hook_subagent_start,
    "pre-compact": hook_pre_compact,
    "session-start": hook_session_start,
    "teammate-idle": hook_teammate_idle,
}

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: auto-mode-hooks.py <command>", file=sys.stderr)
        sys.exit(1)

    cmd = sys.argv[1]
    fn = COMMANDS.get(cmd)
    if not fn:
        print(f"Unknown command: {cmd}", file=sys.stderr)
        sys.exit(1)
    fn()
